#!/bin/bash

# MantraPath Development Environment Setup Script
# This script creates and configures environment files for development

set -e

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Script directory
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
BACKEND_DIR="$PROJECT_ROOT/backend"
FRONTEND_DIR="$PROJECT_ROOT/frontend"

echo -e "${BLUE}🚀 MantraPath Development Environment Setup${NC}"
echo "Project Root: $PROJECT_ROOT"
echo ""

# Function to generate secure secret key
generate_secret_key() {
    openssl rand -hex 32 2>/dev/null || python3 -c "import secrets; print(secrets.token_hex(32))" 2>/dev/null || echo "change-this-secret-key-in-production-$(date +%s)"
}

# Function to generate JWT secret
generate_jwt_secret() {
    openssl rand -base64 64 2>/dev/null | tr -d "=+/" | cut -c1-64 || python3 -c "import secrets; print(secrets.token_urlsafe(64))" 2>/dev/null || echo "change-this-jwt-secret-in-production-$(date +%s)"
}

# Function to prompt for user input with default
prompt_with_default() {
    local prompt="$1"
    local default="$2"
    local var_name="$3"
    
    echo -e "${YELLOW}$prompt${NC}"
    if [ ! -z "$default" ]; then
        echo -e "${BLUE}Default: $default${NC}"
    fi
    read -p "Enter value (or press Enter for default): " input
    
    if [ -z "$input" ]; then
        eval "$var_name='$default'"
    else
        eval "$var_name='$input'"
    fi
}

# Check if .env already exists
if [ -f "$BACKEND_DIR/.env" ]; then
    echo -e "${YELLOW}⚠️  Backend .env file already exists${NC}"
    read -p "Do you want to overwrite it? (y/N): " overwrite
    if [[ ! $overwrite =~ ^[Yy]$ ]]; then
        echo -e "${GREEN}✅ Keeping existing .env file${NC}"
        echo -e "${BLUE}ℹ️  Use 'scripts/dev/update-env.sh' to update specific values${NC}"
        exit 0
    fi
fi

echo -e "${GREEN}📝 Setting up environment configuration...${NC}"
echo ""

# Generate secure keys
SECRET_KEY=$(generate_secret_key)
JWT_SECRET_KEY=$(generate_jwt_secret)

# Prompt for configuration
echo -e "${BLUE}=== Database Configuration ===${NC}"
prompt_with_default "Database Host:" "localhost" DB_HOST
prompt_with_default "Database Port:" "5432" DB_PORT
prompt_with_default "Database Name:" "mantrapath" DB_NAME
prompt_with_default "Database User:" "mantrapath" DB_USER
prompt_with_default "Database Password:" "mantrapath123" DB_PASSWORD

echo ""
echo -e "${BLUE}=== Redis Configuration ===${NC}"
prompt_with_default "Redis Host:" "localhost" REDIS_HOST
prompt_with_default "Redis Port:" "6379" REDIS_PORT

echo ""
echo -e "${BLUE}=== Application Configuration ===${NC}"
prompt_with_default "Frontend URL:" "http://localhost:3000" APP_URL
prompt_with_default "Backend Port:" "8000" BACKEND_PORT

echo ""
echo -e "${BLUE}=== Email Configuration ===${NC}"
echo -e "${YELLOW}Configure email settings for user verification and notifications${NC}"
prompt_with_default "SMTP Server:" "smtp.gmail.com" SMTP_SERVER
prompt_with_default "SMTP Port:" "587" SMTP_PORT
prompt_with_default "SMTP Username (email):" "" SMTP_USERNAME
prompt_with_default "SMTP Password (app password):" "" SMTP_PASSWORD
prompt_with_default "From Email:" "$SMTP_USERNAME" FROM_EMAIL

echo ""
echo -e "${BLUE}=== AI Services (Optional) ===${NC}"
echo -e "${YELLOW}OpenAI API key for enhanced chatbot features (optional)${NC}"
prompt_with_default "OpenAI API Key:" "" OPENAI_API_KEY

# Build DATABASE_URL
DATABASE_URL="postgresql://$DB_USER:$DB_PASSWORD@$DB_HOST:$DB_PORT/$DB_NAME"
REDIS_URL="redis://$REDIS_HOST:$REDIS_PORT"

# Create backend .env file
echo -e "${GREEN}📁 Creating backend .env file...${NC}"
cat > "$BACKEND_DIR/.env" << EOF
# MantraPath Backend Environment Configuration
# Generated by setup-env.sh on $(date)

# Database Configuration  
DATABASE_URL=$DATABASE_URL

# Redis Configuration  
REDIS_URL=$REDIS_URL

# Security
SECRET_KEY=$SECRET_KEY
JWT_SECRET_KEY=$JWT_SECRET_KEY
ALGORITHM=HS256

# Token Expiration (in minutes/days)
ACCESS_TOKEN_EXPIRE_MINUTES=30
REFRESH_TOKEN_EXPIRE_DAYS=7

# Email Configuration
SMTP_SERVER=$SMTP_SERVER
SMTP_PORT=$SMTP_PORT
SMTP_USERNAME=$SMTP_USERNAME
SMTP_PASSWORD=$SMTP_PASSWORD
FROM_EMAIL=$FROM_EMAIL

# Application URL
APP_URL=$APP_URL

# AI Services
OPENAI_API_KEY=$OPENAI_API_KEY

# CORS Settings
CORS_ORIGINS=$APP_URL,http://localhost:5173,http://localhost:$BACKEND_PORT

# Logging
LOG_LEVEL=INFO

# Rate Limiting (requests per minute)
RATE_LIMIT_PER_MINUTE=60

# File Upload Limits
MAX_FILE_SIZE_MB=10
ALLOWED_FILE_TYPES=image/jpeg,image/png,image/gif,image/webp

# Production Settings
DEBUG=true
ENVIRONMENT=development
EOF

# Create frontend .env file if it doesn't exist
if [ ! -f "$FRONTEND_DIR/.env" ]; then
    echo -e "${GREEN}📁 Creating frontend .env file...${NC}"
    cat > "$FRONTEND_DIR/.env" << EOF
# MantraPath Frontend Environment Configuration
# Generated by setup-env.sh on $(date)

# API Configuration
VITE_API_URL=http://localhost:$BACKEND_PORT
VITE_WS_URL=ws://localhost:$BACKEND_PORT

# Application Configuration
VITE_APP_NAME=MantraPath
VITE_APP_VERSION=1.0.0
VITE_ENVIRONMENT=development

# Feature Flags
VITE_ENABLE_ANALYTICS=false
VITE_ENABLE_WEBSOCKETS=true
VITE_ENABLE_PWA=false
EOF
fi

# Create development configuration summary
cat > "$PROJECT_ROOT/.env.summary" << EOF
# MantraPath Development Environment Summary
# Generated on $(date)

=== Configuration Summary ===
Database: $DATABASE_URL
Redis: $REDIS_URL
Frontend: $APP_URL
Backend: http://localhost:$BACKEND_PORT
Email: ${SMTP_USERNAME:-"Not configured"}
OpenAI: ${OPENAI_API_KEY:+"Configured"}${OPENAI_API_KEY:-"Not configured"}

=== Quick Commands ===
Start Development: ./scripts/start.sh
Stop All Services: ./scripts/stop.sh
View Logs: ./scripts/logs.sh
Reset Environment: ./scripts/dev/setup-env.sh

=== Service URLs ===
Frontend: $APP_URL
API Gateway: http://localhost:$BACKEND_PORT
Database: localhost:$DB_PORT
Redis: localhost:$REDIS_PORT
EOF

echo ""
echo -e "${GREEN}✅ Environment setup completed successfully!${NC}"
echo ""
echo -e "${BLUE}📋 Configuration Summary:${NC}"
echo "• Database: $DATABASE_URL"
echo "• Redis: $REDIS_URL"
echo "• Frontend: $APP_URL"
echo "• Backend: http://localhost:$BACKEND_PORT"
echo "• Email: ${SMTP_USERNAME:-"Not configured"}"
echo "• OpenAI: ${OPENAI_API_KEY:+"Configured"}${OPENAI_API_KEY:-"Not configured"}"
echo ""
echo -e "${YELLOW}📝 Next Steps:${NC}"
echo "1. Run: ${GREEN}./scripts/start.sh${NC} to start all services"
echo "2. Visit: ${BLUE}$APP_URL${NC} to access the application"
echo "3. Check: ${BLUE}.env.summary${NC} for quick reference"
echo ""
echo -e "${BLUE}💡 Tips:${NC}"
echo "• Use ${GREEN}./scripts/logs.sh${NC} to view service logs"
echo "• Use ${GREEN}./scripts/stop.sh${NC} to stop all services"
echo "• Configuration saved in: backend/.env and frontend/.env"
